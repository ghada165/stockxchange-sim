-- Module Auth & Utilisateurs
CREATE TABLE users (
    id              VARCHAR(36)     PRIMARY KEY,
    username        VARCHAR(64)     NOT NULL UNIQUE,
    password_hash   VARCHAR(100)    NOT NULL,
    display_name    VARCHAR(100),
    email           VARCHAR(255),
    role            VARCHAR(16)     NOT NULL,
    status          VARCHAR(16)     NOT NULL,
    created_at      TIMESTAMP       NOT NULL
);

-- Module Marche: referentiel des symboles
CREATE TABLE symbols (
    symbol          VARCHAR(16)     PRIMARY KEY,
    name            VARCHAR(100)    NOT NULL,
    reference_price NUMERIC(19,4)   NOT NULL,
    status          VARCHAR(16)     NOT NULL,
    created_at      TIMESTAMP       NOT NULL
);

-- Module Marche: heures d'ouverture (une seule ligne, id = 1)
CREATE TABLE market_settings (
    id              INT             PRIMARY KEY,
    open_time       TIME            NOT NULL,
    close_time      TIME            NOT NULL,
    time_zone       VARCHAR(64)     NOT NULL,
    trading_days    VARCHAR(64)     NOT NULL,
    enforced        BOOLEAN         NOT NULL
);

-- Module Administration: journal d'activite global
CREATE TABLE activity_logs (
    id              BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMP       NOT NULL,
    actor           VARCHAR(64)     NOT NULL,
    action          VARCHAR(32)     NOT NULL,
    details         VARCHAR(500)
);
CREATE INDEX idx_logs_occurred_at ON activity_logs (occurred_at);

